#!/usr/bin/env python3
import ipaddress
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


CONFIG_PATH = Path("/etc/openvpn/server/web.conf")
PKI_PATH = Path("/etc/openvpn/server/web-pki")
UNIT = "openvpn-server@web.service"
OPENVPN = "/usr/sbin/openvpn"
SYSTEMCTL = "/usr/bin/systemctl"
OPENSSL = "/usr/bin/openssl"
CIPHERS = "AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305"


def fail(message):
    print(message, file=sys.stderr)
    raise SystemExit(1)


def run(command, timeout=60):
    try:
        result = subprocess.run(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            universal_newlines=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        fail(str(error))
    if result.returncode:
        fail(result.stdout.strip() or "命令执行失败")
    return result.stdout.strip()


def validate_config(content):
    if len(content.encode("utf-8")) > 16 * 1024:
        fail("服务端配置文件过大")
    lines = content.rstrip("\n").splitlines()
    fixed = [
        r"# Generated by OpenVPN Web Manager",
        r"port [0-9]{1,5}",
        r"proto (?:udp|tcp-server)",
        r"dev tun",
        r"topology subnet",
        r"server (?:[0-9]{1,3}\.){3}[0-9]{1,3} (?:[0-9]{1,3}\.){3}[0-9]{1,3}",
        r"max-clients [0-9]{1,5}",
        r"keepalive [0-9]{1,2} [0-9]{1,4}",
        r"persist-key",
        r"persist-tun",
        r"user nobody",
        r"group nogroup",
        r"dh none",
        r"tls-version-min 1\.2",
        r"remote-cert-tls client",
        r"ca /etc/openvpn/server/web-pki/ca\.crt",
        r"cert /etc/openvpn/server/web-pki/server\.crt",
        r"key /etc/openvpn/server/web-pki/server\.key",
        r"tls-crypt /etc/openvpn/server/web-pki/ta\.key",
        r"ncp-ciphers " + re.escape(CIPHERS),
    ]
    if len(lines) < len(fixed) + 2 or len(lines) > len(fixed) + 5:
        fail("服务端配置结构无效")
    for line, pattern in zip(lines[:len(fixed)], fixed):
        if not re.fullmatch(pattern, line):
            fail("服务端配置包含不支持的指令或参数")
    dns_lines = lines[len(fixed):-1]
    if not 1 <= len(dns_lines) <= 4 or lines[-1] != "verb 3":
        fail("服务端配置结构无效")
    for line in dns_lines:
        match = re.fullmatch(r'push "dhcp-option DNS ([0-9.]+)"', line)
        if not match:
            fail("DNS 配置无效")
        try:
            ipaddress.IPv4Address(match.group(1))
        except ipaddress.AddressValueError:
            fail("DNS 配置无效")


def write_config():
    content = sys.stdin.read()
    validate_config(content)
    CONFIG_PATH.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".web.conf.", dir=str(CONFIG_PATH.parent))
    try:
        os.fchmod(descriptor, 0o644)
        with os.fdopen(descriptor, "w", encoding="utf-8") as target:
            target.write(content)
            target.flush()
            os.fsync(target.fileno())
        os.replace(temporary, str(CONFIG_PATH))
    finally:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass


def generate_pki():
    if PKI_PATH.exists():
        expected = ("ca.crt", "ca.key", "server.crt", "server.key", "ta.key")
        if not PKI_PATH.is_dir() or any(not (PKI_PATH / name).is_file() for name in expected):
            fail("服务端证书目录已存在但文件不完整；请检查 /etc/openvpn/server/web-pki")
        for name in expected:
            os.chmod(str(PKI_PATH / name), 0o600 if name.endswith(".key") else 0o644)
        print("服务端证书已存在")
        return

    if not os.path.isfile(OPENVPN) or not os.path.isfile(OPENSSL):
        fail("需要先安装 OpenVPN 和 OpenSSL")
    parent = PKI_PATH.parent
    parent.mkdir(mode=0o755, parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".web-pki.", dir=str(parent)) as temporary:
        work = Path(temporary)
        ca_config = work / "ca.cnf"
        ca_config.write_text(
            "[req]\n"
            "prompt = no\n"
            "distinguished_name = ca_dn\n"
            "x509_extensions = v3_ca\n"
            "[ca_dn]\n"
            "CN = OpenVPN Web Local CA\n"
            "[v3_ca]\n"
            "basicConstraints = critical,CA:TRUE\n"
            "keyUsage = critical,keyCertSign,cRLSign\n",
            encoding="ascii",
        )
        server_extensions = work / "server.ext"
        server_extensions.write_text(
            "[server_cert]\n basicConstraints=critical,CA:FALSE\n"
            " keyUsage=critical,digitalSignature,keyEncipherment\n"
            " extendedKeyUsage=serverAuth\n subjectKeyIdentifier=hash\n authorityKeyIdentifier=keyid,issuer\n",
            encoding="ascii",
        )
        run([
            OPENSSL, "req", "-x509", "-newkey", "rsa:3072", "-nodes", "-sha256",
            "-days", "3650", "-config", str(ca_config), "-extensions", "v3_ca",
            "-keyout", str(work / "ca.key"), "-out", str(work / "ca.crt"),
        ], timeout=90)
        run([
            OPENSSL, "req", "-new", "-newkey", "rsa:3072", "-nodes", "-sha256",
            "-subj", "/CN=openvpn-web-server",
            "-keyout", str(work / "server.key"), "-out", str(work / "server.csr"),
        ], timeout=90)
        run([
            OPENSSL, "x509", "-req", "-sha256", "-days", "825",
            "-in", str(work / "server.csr"),
            "-CA", str(work / "ca.crt"), "-CAkey", str(work / "ca.key"),
            "-CAcreateserial", "-out", str(work / "server.crt"),
            "-extfile", str(server_extensions), "-extensions", "server_cert",
        ], timeout=30)
        run([OPENVPN, "--genkey", "--secret", str(work / "ta.key")], timeout=15)
        os.mkdir(str(PKI_PATH), 0o700)
        for name in ("ca.crt", "ca.key", "server.crt", "server.key", "ta.key"):
            mode = 0o600 if name.endswith(".key") else 0o644
            os.chmod(str(work / name), mode)
            shutil.copyfile(str(work / name), str(PKI_PATH / name))
            os.chmod(str(PKI_PATH / name), mode)
    print("已生成本机 CA、服务端证书和 tls-crypt 密钥")


def generate_client():
    try:
        payload = json.loads(sys.stdin.read())
    except (TypeError, ValueError):
        fail("客户端参数格式无效")
    if not isinstance(payload, dict) or set(payload) != {"name", "remote", "port", "protocol"}:
        fail("客户端参数格式无效")

    name = payload["name"]
    remote = payload["remote"]
    protocol = payload["protocol"]
    try:
        port = int(payload["port"])
    except (TypeError, ValueError):
        fail("端口无效")
    if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,32}", name):
        fail("客户端名称只能包含字母、数字、下划线和连字符，长度为 1–32")
    if not 1 <= port <= 65535:
        fail("端口范围必须为 1–65535")
    if protocol not in ("udp", "tcp-server"):
        fail("传输协议无效")
    if not isinstance(remote, str) or len(remote) > 253:
        fail("服务器地址无效")
    try:
        ipaddress.ip_address(remote)
    except ValueError:
        labels = remote.rstrip(".").split(".") if remote else []
        if not labels or any(
            not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", label)
            for label in labels
        ):
            fail("服务器地址必须是 IPv4 地址或有效域名")
    if not PKI_PATH.is_dir() or any(
        not (PKI_PATH / filename).is_file()
        for filename in ("ca.crt", "ca.key", "ta.key")
    ):
        fail("服务端 CA 尚未初始化，请先启动一次 OpenVPN 服务")

    with tempfile.TemporaryDirectory(prefix=".web-client.", dir=str(PKI_PATH.parent)) as temporary:
        work = Path(temporary)
        extensions = work / "client.ext"
        extensions.write_text(
            "[client_cert]\n"
            "basicConstraints=critical,CA:FALSE\n"
            "keyUsage=critical,digitalSignature\n"
            "extendedKeyUsage=clientAuth\n"
            "subjectKeyIdentifier=hash\n"
            "authorityKeyIdentifier=keyid,issuer\n",
            encoding="ascii",
        )
        run([
            OPENSSL, "req", "-new", "-newkey", "rsa:2048", "-nodes", "-sha256",
            "-subj", "/CN={}".format(name),
            "-keyout", str(work / "client.key"), "-out", str(work / "client.csr"),
        ], timeout=90)
        serial = secrets.token_hex(16)
        run([
            OPENSSL, "x509", "-req", "-sha256", "-days", "825",
            "-in", str(work / "client.csr"),
            "-CA", str(PKI_PATH / "ca.crt"), "-CAkey", str(PKI_PATH / "ca.key"),
            "-set_serial", "0x{}".format(serial),
            "-out", str(work / "client.crt"),
            "-extfile", str(extensions), "-extensions", "client_cert",
        ], timeout=30)
        cert = (work / "client.crt").read_text(encoding="ascii").strip()
        key = (work / "client.key").read_text(encoding="ascii").strip()
        ca = (PKI_PATH / "ca.crt").read_text(encoding="ascii").strip()
        tls_crypt = (PKI_PATH / "ta.key").read_text(encoding="ascii").strip()
        proto = "udp" if protocol == "udp" else "tcp"
        profile = "\n".join([
            "client",
            "dev tun",
            "proto {}".format(proto),
            "remote {} {} ".format(remote, port) + proto,
            "resolv-retry infinite",
            "nobind",
            "persist-key",
            "persist-tun",
            "remote-cert-tls server",
            "auth-nocache",
            "tls-version-min 1.2",
            "ncp-ciphers {}".format(CIPHERS),
            "verb 3",
            "<ca>",
            ca,
            "</ca>",
            "<cert>",
            cert,
            "</cert>",
            "<key>",
            key,
            "</key>",
            "<tls-crypt>",
            tls_crypt,
            "</tls-crypt>",
            "",
        ])
        print(json.dumps({"profile": profile}))


def service(action):
    if action == "status":
        try:
            result = subprocess.run(
                [SYSTEMCTL, "is-active", UNIT],
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                universal_newlines=True,
                timeout=8,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as error:
            fail(str(error))
        print(result.stdout.strip() or "unknown")
        return
    if action in ("start", "restart"):
        if not CONFIG_PATH.is_file():
            fail("服务端配置不存在，请先保存配置")
        if not PKI_PATH.is_dir():
            fail("服务端证书不存在")
    try:
        result = subprocess.run(
            [SYSTEMCTL, action, UNIT],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            universal_newlines=True,
            timeout=75,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        fail(str(error))
    if result.returncode:
        details = result.stdout.strip()
        try:
            logs = subprocess.run(
                ["/usr/bin/journalctl", "-u", UNIT, "-n", "30", "--no-pager"],
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                universal_newlines=True,
                timeout=10,
                check=False,
            )
            if logs.stdout.strip():
                details = "{}\n{}".format(details, logs.stdout.strip())
        except (OSError, subprocess.TimeoutExpired):
            pass
        fail(details or "systemd 服务操作失败")
    print(result.stdout.strip() or "操作已完成")


def main():
    if os.geteuid() != 0:
        fail("此程序必须由 sudo 运行")
    if len(sys.argv) != 2:
        fail("只允许一个预设操作")
    action = sys.argv[1]
    if action == "init-pki":
        generate_pki()
    elif action == "write-config":
        write_config()
    elif action == "issue-client":
        generate_client()
    elif action in ("status", "start", "stop", "restart"):
        service(action)
    else:
        fail("不支持的操作")


if __name__ == "__main__":
    main()
